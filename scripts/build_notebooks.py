"""Build lessons/NN-*/lesson.ipynb for every finished chapter, from its README, run.py and practice.

    make notebooks            write every notebook
    make notebooks-check      fail if a committed notebook is stale (part of `make release-check`)

A notebook is not a second copy to maintain: it is generated. The README's teaching sections
become text cells, run.py is split into one code cell per `step(...)`, and the practice
cells run the chapter check and the exercise grader in the notebook itself. Predictions work in
notebooks too (lantern.learn asks with input() under Jupyter). Edit the README or run.py, then run
`make notebooks`.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAFT = "<!-- status: draft -->"
BEFORE_CODE = ("## The scene", "## The concept", "## How it works")
AFTER_CODE = ("## The nuances", "## Try this")


def sections(readme: str) -> dict[str, str]:
    """README text by `## ` heading, heading included."""
    parts = re.split(r"(?m)^(?=## )", readme)
    return {p.splitlines()[0].strip(): p.strip() for p in parts if p.startswith("## ")}


def split_steps(code: str) -> list[str]:
    """run.py cut before every top-level `step(` call. One chunk when steps are nested."""
    lines = code.splitlines()
    cuts = [i for i, line in enumerate(lines) if line.startswith("step(")]
    if not cuts:
        return [code.strip()]
    # Move each cut up over comments and blank lines directly above the step(...) call.
    adjusted = []
    for c in cuts:
        while c > 0 and (lines[c - 1].startswith("#") or not lines[c - 1].strip()):
            c -= 1
        adjusted.append(c)
    bounds = [0, *adjusted, len(lines)]
    chunks = ["\n".join(lines[a:b]).strip() for a, b in zip(bounds, bounds[1:], strict=False)]
    return [c for c in chunks if c]


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": _lines(text)}


def code(text: str) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": _lines(text),
    }


def _lines(text: str) -> list[str]:
    out = text.strip("\n").splitlines(keepends=True)
    return out


def step_title(chunk: str) -> str | None:
    m = re.search(r'^step\(\s*f?"([^"]+)"', chunk, re.M)
    return m.group(1) if m else None


def build(lesson: Path) -> dict | None:
    readme = (lesson / "README.md").read_text(encoding="utf-8")
    if DRAFT in readme or not (lesson / "practice" / "practice.yaml").exists():
        return None
    n = lesson.name[:2]
    title = readme.splitlines()[0].lstrip("# ").strip()
    secs = sections(readme)
    # Links in the README are relative to the lesson folder, as is the notebook: they still work.
    cells = [
        md(
            f"# {title}\n\nThe notebook version of [`README.md`](README.md) and "
            "[`run.py`](run.py), generated by `make notebooks`. Run the cells in order. The "
            "lesson stops to ask for your predictions; answer in the box under the cell."
        ),
        code(
            "# Setup: tell LANTERN which chapter this is, and give the lesson code the __file__\n"
            "# a script has (the kernel runs in this lesson's folder).\n"
            "import os\n"
            f'os.environ["LANTERN_CHAPTER"] = "{n}"\n'
            '__file__ = os.path.abspath("run.py")'
        ),
    ]
    cells += [md(secs[h]) for h in BEFORE_CODE if h in secs]
    run = (lesson / "run.py").read_text(encoding="utf-8")
    run = re.sub(r'^"""[\s\S]*?"""\n', "", run, count=1)  # the module docstring
    future = re.findall(r"(?m)^from __future__ import .+$", run)
    run = re.sub(r"(?m)^from __future__ import .+\n", "", run)
    cells.append(md("## The lesson\n\nThe code from `run.py`, one cell per step."))
    for i, chunk in enumerate(split_steps(run)):
        if i == 0 and future:
            chunk = "\n".join(future) + "\n\n" + chunk
        if (t := step_title(chunk)) and i:
            cells.append(md(f"### {t}"))
        cells.append(code(chunk))
    cells += [md(secs[h]) for h in AFTER_CODE if h in secs]
    cells += [
        md(
            "## Master it\n\n"
            + secs.get("## Master it", "").removeprefix("## Master it").strip()
            + "\n\nThe cells below run the same commands inside this notebook."
        ),
        md("### Check yourself"),
        code(f"%run ../../scripts/learn.py quiz {n}"),
        md(
            "### Build it\n\nOpen [`practice/exercise.py`](practice/exercise.py) beside this "
            "notebook, fill in the TODOs, save, and run the grader. Hints come one at a time."
        ),
        code(f"%run ../../scripts/learn.py exercise {n}"),
        code(f"%run ../../scripts/learn.py hint {n}"),
        md(
            "### Break it\n\nThe challenges are checked against your latest run of the lesson "
            "cells above (or of `make lesson`). Change the code, rerun the lesson, then check."
        ),
        code(f"%run ../../scripts/learn.py challenge {n}"),
        code("%run ../../scripts/learn.py progress"),
    ]
    if "## What the evidence now shows" in secs:
        cells.append(md(secs["## What the evidence now shows"]))
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def render(nb: dict) -> str:
    return json.dumps(nb, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    check = "--check" in sys.argv
    lessons = sorted(p for p in (ROOT / "lessons").glob("[0-9][0-9]-*") if p.is_dir())
    built, stale = 0, []
    for lesson in lessons:
        nb = build(lesson)
        out = lesson / "lesson.ipynb"
        if nb is None:
            continue
        built += 1
        text = render(nb)
        if check:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                stale.append(out.relative_to(ROOT))
        else:
            out.write_text(text, encoding="utf-8")
    if check:
        for s in stale:
            print(f"out of date: {s}")
        print(f"notebooks: checked {built}, {len(stale)} out of date (fix: make notebooks)")
        return 1 if stale or not built else 0
    print(f"notebooks: wrote {built}")
    return 0 if built else 1


if __name__ == "__main__":
    sys.exit(main())
